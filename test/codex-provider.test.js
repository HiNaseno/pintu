test('queue serializes operations and continues after a failure', async () => {
  const provider = new CodexProvider();
  const order = [];
  const first = provider.enqueue(async () => { order.push(1); await new Promise(resolve => setTimeout(resolve, 20)); order.push(2); throw new Error('failed'); });
  const second = provider.enqueue(async () => { order.push(3); return 4; });
  await assert.rejects(first);
  assert.equal(await second, 4);
  assert.deepEqual(order, [1, 2, 3]);
  assert.equal(provider.pending, 0);
});

test('image arrays preserve attachment order and identify the mask after all references', async t => {
  const png = await sharp({ create: { width: 3, height: 3, channels: 4, background: 'cyan' } }).png().toBuffer();
  const second = await sharp({ create: { width: 4, height: 4, channels: 4, background: 'red' } }).png().toBuffer();
  const mask = await sharp({ create: { width: 3, height: 3, channels: 4, background: {r:0,g:0,b:0,alpha:0} } }).png().toBuffer();
  const { provider, root } = await fixture(t, `
    const fs=require('node:fs'); const path=require('node:path'); const args=process.argv.slice(2);
    const attachments=args.flatMap((a,i)=>a==='-i'?[args[i+1]]:[]);
    let input=''; process.stdin.on('data',chunk=>input+=chunk);
    process.stdin.on('end',()=>{
      fs.writeFileSync(path.join(__dirname,'captured.json'),JSON.stringify({input,attachments:attachments.map(file=>({name:path.basename(file),data:fs.readFileSync(file).toString('base64')}))}));
      fs.writeFileSync('generated.png',Buffer.from('${png.toString('base64')}','base64'));
      fs.writeFileSync(args[args.indexOf('-o')+1],'generated.png');
    });
  `);
  await provider.images.edit({image:[new File([png],'one.png'),new File([second],'two.png')],mask:new File([mask],'mask.png'),prompt:'Only change the background'});
  const captured=JSON.parse(await fs.readFile(path.join(root,'captured.json'),'utf8'));
  assert.deepEqual(captured.attachments.map(image=>image.name),['input-1.png','input-2.png','mask.png']);
  assert.deepEqual(await Promise.all(captured.attachments.map(async image=>(await sharp(Buffer.from(image.data,'base64')).metadata()).width)),[3,4,3]);
  assert.match(captured.input,/第 3 张附件是编辑蒙版，作用于第 1 张附件/);
  assert.match(captured.input,/第 1 张附件是编辑目标/);
  assert.match(captured.input,/根据画面要求选择主要参考/);
  assert.match(captured.input,/不同款式或材质可以分别来自不同附件/);
  assert.doesNotMatch(captured.input,/第 1 张是主要参考/);
  assert.equal((await sharp(Buffer.from(captured.attachments[2].data,'base64')).raw().toBuffer())[3],0);
  await provider.images.edit({image:[new File([png],'one.png'),new File([second],'two.png')],prompt:'Use the material from attachment 2; show both variants.'});
  const multiple=JSON.parse(await fs.readFile(path.join(root,'captured.json'),'utf8'));
  assert.deepEqual(multiple.attachments.map(image=>image.name),['input-1.png','input-2.png']);
  assert.match(multiple.input,/前 2 张附件按上传顺序编号/);
  assert.match(multiple.input,/画面要求多款同框时，分别准确还原对应附件/);
  assert.match(multiple.input,/Use the material from attachment 2/);
  assert.doesNotMatch(multiple.input,/第 1 张是主要参考|第 1 张附件是编辑目标|编辑蒙版/);
  await provider.images.edit({image:new File([png],'one.png'),mask:new File([mask],'mask.png'),prompt:'Edit a selected area'});
  const single=JSON.parse(await fs.readFile(path.join(root,'captured.json'),'utf8'));
  assert.equal(single.attachments.length,2);
  assert.match(single.input,/第 2 张附件是编辑蒙版，作用于第 1 张附件/);
  await assert.rejects(provider.images.edit({mask:new File([mask],'mask.png'),prompt:'edit'}),/需要原始图片/);
});

test('CLI receives only runtime environment and never gateway or unrelated service secrets', async t => {
  const blocked = ['OPC_GATEWAY_TOKEN','OPC_ENCRYPTION_KEY','OPC_DEVICE_CODE','opc_lower_secret','SESSION_SECRET','DATABASE_URL','REDIS_URL','OTHER_SERVICE_TOKEN','AWS_SECRET_ACCESS_KEY','OPENAI_API_KEY','OPENAI_BASE_URL','GOOGLE_APPLICATION_CREDENTIALS'];
  const previous = Object.fromEntries(blocked.map(name=>[name,process.env[name]]));
  for(const name of blocked)process.env[name]='must-never-reach-cli';
  t.after(()=>{for(const name of blocked){if(previous[name]===undefined)delete process.env[name];else process.env[name]=previous[name];}});
  const {provider}=await fixture(t, `process.stdout.write(JSON.stringify({keys:Object.keys(process.env),path:Boolean(process.env.PATH),home:Boolean(process.env.HOME)}));`);
  const {stdout}=await provider.run(['test-env']);
  const captured=JSON.parse(stdout);
  for(const name of blocked)assert.ok(!captured.keys.includes(name),`${name} must be removed`);
  assert.ok(!captured.keys.some(name=>name.toUpperCase().startsWith('OPC_')));
  assert.equal(captured.path,true);assert.equal(captured.home,true);
});

