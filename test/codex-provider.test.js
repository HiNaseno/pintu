test('persistent image completion can be queried after reload without another CLI invocation',async t=>{
  const {provider,root,png,directory,request}=await persistentFixture(t);
  const generated=await provider.images.generate(request);
  assert.equal(generated.engineTaskId,'local-task-1');assert.equal(generated.outcome,'SUCCEEDED');assert.equal(generated.completedCount,1);
  assert.deepEqual(Buffer.from(generated.data[0].b64_json,'base64'),png);
  const state=JSON.parse(await fs.readFile(path.join(directory,'engine-result.json'),'utf8'));
  assert.equal(state.outcome,'SUCCEEDED');assert.equal(state.completedCount,1);
  assert.equal(state.remoteThreadId,'12345678-1234-4234-8234-123456789abc');assert.equal(state.remoteTaskId,'native-task-1');
  assert.equal(state.diagnostic.reason,'IMAGE_COMMITTED');assert.equal(state.diagnostic.exitCode,0);
  assert.equal(state.diagnostic.timedOut,false);assert.equal(state.diagnostic.spawnFailed,false);
  assert.deepEqual(state.diagnostic.eventCounts,{'thread.started':1,'task.started':1});
  assert.ok(!JSON.stringify(state).includes(request.prompt));assert.ok(!('stdout' in state));assert.ok(!('stderr' in state));
  assert.equal((await fs.stat(path.join(directory,'engine-result.json'))).mode&0o777,0o600);
  assert.equal((await fs.stat(directory)).mode&0o777,0o700);
  assert.ok((await fs.stat(path.join(directory,'work'))).isDirectory());
  const reloaded=new CodexProvider({binary:'/not-present/never-run'});
  const queried=await reloaded.queryImageTask(directory);
  assert.deepEqual(queried,generated);
  assert.deepEqual(await reloaded.images.generate(request),generated);
  assert.equal(await fs.readFile(path.join(root,'calls'),'utf8'),'1');
  await assert.rejects(reloaded.images.generate({...request,prompt:'different parameters'}),{code:'ENGINE_TASK_CONFLICT'});
  await assert.rejects(reloaded.images.generate({...request,localEngineTaskId:'different-task'}),{code:'ENGINE_TASK_CONFLICT'});
  assert.equal(await fs.readFile(path.join(root,'calls'),'utf8'),'1');
});

