test('event persistence failures record exit evidence but never accept a generated image as settled',async t=>{
  const {provider,root,directory,request}=await persistentFixture(t);
  const originalRename=fs.rename;
  let failed=false;
  fs.rename=async(from,to)=>{
    if(to===path.join(directory,'engine-result.json')){
      const state=JSON.parse(await fs.readFile(from,'utf8'));
      if(state.stage==='ENGINE_RUNNING'&&!failed){failed=true;throw Object.assign(new Error('private-storage-error'),{code:'EIO'});}
    }
    return originalRename(from,to);
  };
  try{await assert.rejects(provider.images.generate(request),{code:'ENGINE_RESULT_UNKNOWN'});}
  finally{fs.rename=originalRename;}
  const state=JSON.parse(await fs.readFile(path.join(directory,'engine-result.json'),'utf8'));
  assert.equal(state.outcome,'UNKNOWN');assert.ok(!('completedCount' in state));
  assert.equal(state.diagnostic.reason,'EVENT_PERSIST_FAILED');assert.equal(state.diagnostic.eventPersistenceFailed,true);
  assert.equal(state.diagnostic.exitCode,0);assert.deepEqual(state.diagnostic.eventCounts,{'thread.started':1,'task.started':1});
  assert.ok(!JSON.stringify(state).includes('private-storage-error'));
  assert.ok((await fs.stat(path.join(directory,'work','generated.png'))).size>0);
  assert.equal((await provider.queryImageTask(directory)).outcome,'UNKNOWN');
  await assert.rejects(provider.images.generate(request),{code:'ENGINE_RESULT_UNKNOWN'});
  assert.equal(await fs.readFile(path.join(root,'calls'),'utf8'),'1');
});

