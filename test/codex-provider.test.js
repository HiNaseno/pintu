test('text requests pass schema and uploaded images without shell interpolation', async t => {
  const { provider, root } = await fixture(t, `
    const fs = require('node:fs');
    const args = process.argv.slice(2);
    if (args.includes('--dangerously-bypass-approvals-and-sandbox')) process.exit(5);
    if (args[args.indexOf('-m') + 1] !== 'gpt-6.1-sol') process.exit(8);
    if (!args.includes('model_reasoning_effort=\"medium\"')) process.exit(9);
    if (args[args.indexOf('image_generation')-1] !== '--disable') process.exit(10);
    if (!fs.existsSync(args[args.indexOf('-i') + 1])) process.exit(6);
    if (JSON.parse(fs.readFileSync(args[args.indexOf('--output-schema') + 1])).type !== 'object') process.exit(7);
    let input=''; process.stdin.on('data', chunk => input += chunk);
    process.stdin.on('end', () => fs.writeFileSync(args[args.indexOf('-o') + 1], JSON.stringify({ suggestion: input })));
  `);
  const data = await sharp({ create: { width: 2, height: 2, channels: 3, background: 'white' } }).png().toBuffer();
  const payload = `test; touch ${root}/injected; $(echo unsafe)`;
  const result = await provider.responses.create({ input: [{ content: [{ type: 'input_text', text: payload }, { type: 'input_image', image_url: `data:image/png;base64,${data.toString('base64')}` }] }], text: { format: { schema: { type: 'object' } } } });
  assert.ok(JSON.parse(result.output_text).suggestion.includes(payload));
  await assert.rejects(fs.stat(path.join(root, 'injected')), { code: 'ENOENT' });
});

